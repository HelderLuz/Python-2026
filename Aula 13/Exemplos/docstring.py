def calcular_area_retangulo(base: float, altura: float) -> float:
    """
    Calcula a área de um retângulo.

    Parâmetros:
    - base (float): Comprimento da base do retângulo.
    - altura (float): Altura do retângulo.

    Retorna:
    - float: A área calculada do retângulo.

    Exemplo:
    calcular_area_retangulo(5, 3)
    15
    """
    return base * altura

